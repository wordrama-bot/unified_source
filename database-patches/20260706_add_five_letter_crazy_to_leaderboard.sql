            COALESCE(sum(a.games_won_in_6), (0)::numeric) AS alltime_games_won_in_6
           FROM (members m
             LEFT JOIN _mv_wordle_alltime_leaderboard a ON ((a.player = m.player)))
          GROUP BY m.team
        ), daily AS (
         SELECT m.team AS team_id,
            COALESCE(sum(d.games_played), (0)::numeric) AS daily_games_played,
            COALESCE(sum(d.games_won), (0)::numeric) AS daily_games_won,
            COALESCE(sum(d.games_lost), (0)::numeric) AS daily_games_lost,
            COALESCE(sum(d.games_won_in_1), (0)::numeric) AS daily_games_won_in_1,
            COALESCE(sum(d.games_won_in_2), (0)::numeric) AS daily_games_won_in_2,
