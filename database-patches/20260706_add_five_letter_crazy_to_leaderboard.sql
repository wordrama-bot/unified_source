            COALESCE(sum(w.games_won_in_5), (0)::numeric) AS weekly_games_won_in_5,
            COALESCE(sum(w.games_won_in_6), (0)::numeric) AS weekly_games_won_in_6
           FROM (members m
             LEFT JOIN _mv_wordle_weekly_leaderboard w ON (((w.player = m.player) AND (w.week = (EXTRACT(week FROM now()))::bigint) AND (w.year = (EXTRACT(year FROM now()))::bigint))))
          GROUP BY m.team
        ), monthly AS (
         SELECT m.team AS team_id,
            COALESCE(sum(mo.games_played), (0)::numeric) AS monthly_games_played,
            COALESCE(sum(mo.games_won), (0)::numeric) AS monthly_games_won,
