            COALESCE(sum(mo.games_won_in_6), (0)::numeric) AS monthly_games_won_in_6
           FROM (members m
             LEFT JOIN _mv_wordle_monthly_leaderboard mo ON (((mo.player = m.player) AND (mo.month = (EXTRACT(month FROM now()))::bigint) AND (mo.year = (EXTRACT(year FROM now()))::bigint))))
          GROUP BY m.team
        ), yearly AS (
