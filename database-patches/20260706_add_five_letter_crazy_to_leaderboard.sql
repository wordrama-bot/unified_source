         SELECT _team_member.team,
            _team_member.player
           FROM _team_member
        ), alltime AS (
         SELECT m.team AS team_id,
            count(m.player) AS member_count,
            COALESCE(avg(a.level), (0)::numeric) AS average_level,
            COALESCE(sum(a.coin_balance), (0)::numeric) AS total_coins,
            COALESCE(sum(a.games_played), (0)::numeric) AS alltime_games_played,
            COALESCE(sum(a.games_won), (0)::numeric) AS alltime_games_won,
            COALESCE(sum(a.games_lost), (0)::numeric) AS alltime_games_lost,
            COALESCE(sum(a.games_won_in_1), (0)::numeric) AS alltime_games_won_in_1,
            COALESCE(sum(a.games_won_in_2), (0)::numeric) AS alltime_games_won_in_2,
            COALESCE(sum(a.games_won_in_3), (0)::numeric) AS alltime_games_won_in_3,
            COALESCE(sum(a.games_won_in_4), (0)::numeric) AS alltime_games_won_in_4,
