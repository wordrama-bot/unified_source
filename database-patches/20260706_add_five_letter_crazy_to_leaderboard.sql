            COALESCE(sum(d.games_won_in_6), (0)::numeric) AS daily_games_won_in_6
           FROM (members m
             LEFT JOIN _mv_wordle_daily_leaderboard d ON (((d.player = m.player) AND (d.day = (EXTRACT(day FROM now()))::bigint) AND (d.month = (EXTRACT(month FROM now()))::bigint) AND (d.year = (EXTRACT(year FROM now()))::bigint))))
          GROUP BY m.team
        ), weekly AS (
         SELECT m.team AS team_id,
            COALESCE(sum(w.games_played), (0)::numeric) AS weekly_games_played,
            COALESCE(sum(w.games_won), (0)::numeric) AS weekly_games_won,
            COALESCE(sum(w.games_lost), (0)::numeric) AS weekly_games_lost,
            COALESCE(sum(w.games_won_in_1), (0)::numeric) AS weekly_games_won_in_1,
            COALESCE(sum(w.games_won_in_2), (0)::numeric) AS weekly_games_won_in_2,
